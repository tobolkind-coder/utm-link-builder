const fs = require('fs');
const path = require('path');

const pkgStat = fs.statSync('package.json');
const pkgMtime = pkgStat.mtime;

const dirs = fs.readdirSync('node_modules');
dirs.forEach(d => {
  try {
    const stat = fs.statSync(path.join('node_modules', d));
    if (stat.isDirectory() && stat.mtime > pkgMtime) {
      console.log(d + ' | ' + stat.mtime.toISOString());
    }
  } catch(e) {}
});